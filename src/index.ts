/**
 * Application entry point (CEF Lambda handler).
 *
 * `npm run dev` / `npm start` run this file with `--local`, which starts CEF's local
 * HTTP server on http://localhost:8888 (pass a port after --local to change it).
 * The same exported `handler` could be deployed to AWS Lambda unchanged.
 */
import 'reflect-metadata';
import { loadEnv, startDevServer } from 'commoneventframework';

// Loads .env (and .env.local) before anything reads the configuration.
const envReady = loadEnv();

import path from 'node:path';
// Registers every x-handler / x-inputParser referenced in root.yaml (generated by `npm run codegen`).
import './generated/HandlerRegistry';
import { disposeContainer } from './bootstrap/container';
import { createHttpPipeline } from './http/pipeline';
import { logger } from './shared/logging/logger';

export const handler = createHttpPipeline({
  envReady,
  rootYamlPath: path.join(__dirname, 'root.yaml'),
});

if (process.argv.includes('--local')) {
  startDevServer(handler);

  const shutdown = (signal: string): void => {
    logger.info('shutting down', { signal });
    disposeContainer().finally(() => process.exit(0));
  };
  process.once('SIGINT', () => shutdown('SIGINT'));
  process.once('SIGTERM', () => shutdown('SIGTERM'));
}
